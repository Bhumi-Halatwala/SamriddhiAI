def detect_service_intent(text: str) -> str | None:
    """Detects banking service intent from free user query across 12 Indian languages."""
    text_lower = text.lower().strip()
    words = set(re.findall(r"[a-zA-Z0-9_\u0900-\u0D7F]+", text_lower))
    norm_text = " " + " ".join(words) + " "

    # 1. KYC Assistance
    if any(k in words for k in ["kyc", "केवाईसी", "કેવાયસી", "কেওয়াইসি", "కేవైసీ", "கேஒய்சி", "ಕೆವೈಸಿ"]):
        if words & {"update", "अपडेट", "અપડેટ", "doc", "docs", "document", "documents", "दस्तावेज", "दस्तावेज़", "દસ્તાવેજ", "video", "वीडियो", "વિડિયો", "rekyc", "re-kyc", "aadhaar", "pan", "आधार", "पैन", "આધાર", "પાન"}:
            return "intent_kyc_update"
        return "intent_kyc_status"

    # 2. Card Security (Block Debit Card)
    if (words & {"block", "ब्लॉक", "બ્લોક", "freeze", "lost", "stolen", "चोरी", "ખોવાઈ", "खो", "बंद", "બંધ"}) and (words & {"card", "debit", "atm", "कार्ड", "કાર્ડ", "एटीएम", "એટીએમ"}):
        return "intent_block_card"

    # 3. PIN Reset
    if (words & {"pin", "पिन", "પિન"}) and (words & {"reset", "change", "forgot", "new", "रीसेट", "રીસેટ", "बदलना", "ભૂલી", "નવો", "नया", "generate", "सेट"}):
        return "intent_pin_reset"

    # 4. Account Balance
    if words & {"balance", "बैलेंस", "બેલેન્સ", "शिल्लक", "ব্যালেন্স", "బ్యాలెన్స్", "இருப்பு", "ಬ್ಯಾಲೆನ್ಸ್", "ਬਕਾਇਆ"}:
        return "intent_balance"

    # 5. Statement / Recent Transactions
    if words & {"statement", "mini", "transactions", "transaction", "स्टेटमेंट", "मिनी", "સ્ટેટમેન્ટ", "મિની", "लेनदेन", "વ્યવહારો", "પાસબુક", "पासबुक", "ઇતિહાસ", "इतिहास"}:
        return "intent_mini_statement"

    # 6. Credit Score / CIBIL
    if words & {"cibil", "सिबिल", "સિબિલ", "bureau", "ब्यूरो", "બ્યુરો"} or (words & {"score", "स्कोर", "સ્કોર"} and words & {"credit", "क्रेडिट", "ક્રેડિટ"}):
        return "intent_credit_score"

    # 7. Loans (Apply vs Existing)
    if words & {"loan", "loans", "लोन", "લોન", "कर्ज", "ઋણ"}:
        if words & {"apply", "new", "need", "want", "take", "chahiye", "नया", "નવી", "જોઈએ", "લેવી", "चाहिए", "लेना", "અરજી", "आवेदन", "लेनी", "લેવું"}:
            return "intent_apply_loan"
        if words & {"active", "existing", "current", "my", "chaloo", "chalu", "मौजूदा", "સક્રિય", "હાલની", "મારી", "मेरी", "કઈ", "कौन", "kitni", "કેટલી", "emi", "किस्त", "હપ્તો", "हफ्ता"}:
            return "intent_existing_loans"
        return "intent_apply_loan"

    # 8. Branch Timings & IFSC
    if words & {"branch", "timing", "timings", "hours", "ifsc", "शाखा", "समय", "આઈએફએસસી", "આઇએફએસસી", "સમય", "holiday", "रजा", "રજા"}:
        return "intent_branch"

    # 9. Interest Rates
    if (words & {"interest", "rate", "rates", "ब्याज", "दर", "વ્યાજ", "દર"}) or (words & {"fd", "rd", "एफडी", "आरडी", "એફડી", "આરડી"}):
        return "intent_rates"

    # 10. Helpline
    if words & {"helpline", "care", "support", "tollfree", "toll", "free", "contact", "हेल्पलाइन", "कस्टमर", "केयर", "સહાયતા", "ટોલ", "કસ્ટમર", "हेल्प", "मदद", "મદદ", "help"}:
        return "intent_helpline"

    # Fallback to phrase matching in INTENT_KEYWORDS
    for intent_name, phrases in INTENT_KEYWORDS.items():
        for phrase in phrases:
            phrase = phrase.lower().strip()
            if " " in phrase:
                if phrase in text_lower or f" {phrase} " in norm_text:
                    return intent_name
            else:
                if phrase in words:
                    return intent_name
    return None


