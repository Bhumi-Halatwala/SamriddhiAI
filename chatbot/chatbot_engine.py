def extract_amount(text: str):
    """Pulls a rupee amount out of free text across Indian languages."""
    text = (
        text.lower()
        .replace(",", "")
        .replace("₹", "")
        .replace("rs.", "")
        .replace("rs", "")
        .translate(DEVANAGARI_DIGITS)
        .strip()
    )
    words = re.findall(r"[a-zA-Z0-9_.\u0900-\u0D7F]+", text)
    replaced_words = [WORD_NUMS.get(w, w) for w in words]
    norm_text = " ".join(replaced_words)

    match = re.search(rf"(\d+(?:\.\d+)?)\s*({UNITS_PATTERN})?", norm_text)
    if not match:
        return False, None

    number = float(match.group(1))
    unit = match.group(2)
    if unit and unit in MULTIPLIERS:
        number *= MULTIPLIERS[unit]

    if number <= 0:
        return False, None
    return True, int(number)


def extract_years(text: str):
    """Extract a loan tenure in years from multilingual free text."""
    normalized = text.lower().translate(DEVANAGARI_DIGITS)
    match = re.search(
        r"(?:for|over|of|में|के लिए|માટે|க்கு|க்காக)?\s*(\d+(?:\.\d+)?)\s*"
        r"(?:years?|year|yrs?|वर्ष|साल|वर्षों|વર્ષ|વર્ષો|বছর|సంవత్సరాలు|ஆண்டுகள்|ವರ್ಷ|വർഷം|ਸਾਲ|ବର୍ଷ)",
        normalized,
    )
    if not match:
        return False, None
    years = float(match.group(1))
    if years <= 0 or years > 30:
        return False, None
    return True, years


