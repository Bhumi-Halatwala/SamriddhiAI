class ChatbotEngine:
    LOAN_FLOW = [
        ("ask_income", extract_amount, "income"),
        ("ask_purpose", extract_purpose, "purpose"),
        ("ask_amount", extract_amount, "amount"),
        ("ask_consent", extract_consent, "consent"),
    ]

    SUPPORTED_LANGUAGES = {
        "hi", "gu", "en", "mr", "bn", "te", "ta", "kn", "ml", "pa", "or", "hi_latin"
    }
    LOAN_RATES = {
        "education": 8.50,
        "auto": 8.90,
        "home": 8.50,
        "personal": 10.25,
        "business": 11.50,
    }

    def __init__(self, language: str = "hi", customer_id: str = "CUST000001"):
        self.language = language if language in self.SUPPORTED_LANGUAGES else "hi"
        self.customer_id = customer_id
        self.dm = DataManager.get_instance()
        self.profile = self.dm.get_profile(self.customer_id)

        # Mode: 'general' (multi-service assistance) or 'loan_onboarding' (step-by-step application)
        self.mode = "general"
        self.step_index = 0
        self.slots = {}
        self.finished = False
        self.retry_count = 0
        self.last_loan_offer = None

    def set_language(self, language: str):
        if language in self.SUPPORTED_LANGUAGES:
            self.language = language
        else:
            self.language = "hi"

    def set_customer(self, customer_id: str):
        self.customer_id = customer_id
        self.profile = self.dm.get_profile(customer_id)
        self.mode = "general"
        self.step_index = 0
        self.slots = {}
        self.finished = False
        self.retry_count = 0
        self.last_loan_offer = None

    def _msg(self, key: str, **kwargs) -> str:
        lang_dict = MESSAGES.get(key, {})
        template = lang_dict.get(self.language, lang_dict.get("hi", lang_dict.get("en", "")))
        return template.format(**kwargs) if kwargs else template

    def start(self) -> str:
        """Initial welcome greeting for the assistant."""
        return self._msg("greeting")

    def progress(self) -> tuple[int, int]:
        if self.mode == "loan_onboarding":
            return self.step_index, len(self.LOAN_FLOW)
        return 0, 0

    def _get_next_loan_question(self) -> str:
        """Finds the next unanswered slot in loan onboarding, or completes the application if all are answered."""
        while self.step_index < len(self.LOAN_FLOW):
            state_name, _, slot_name = self.LOAN_FLOW[self.step_index]
            if slot_name not in self.slots:
                return self._msg(state_name)
            self.step_index += 1

        # All slots collected! Complete loan application
        self.finished = True
        self.mode = "general"
        raw_purpose = self.slots.get("purpose", "personal")
        lang_purposes = PURPOSE_DISPLAY.get(self.language, PURPOSE_DISPLAY["hi"])
        disp_purpose = lang_purposes.get(raw_purpose, raw_purpose.title())
        req_amount = self.slots.get("amount", 100000)
        # Eligibility calculation
        income = self.slots.get("income", self.profile.get("monthly_income", 35000))
        eligible_amount = min(req_amount, income * 12)
        eligible_amount = max(eligible_amount, req_amount)
        self.last_loan_offer = {
            "purpose": raw_purpose,
            "approved_amount": int(eligible_amount),
            "requested_amount": int(req_amount),
        }
        return self._msg("done_eligible", purpose=disp_purpose, max_amount=eligible_amount)

    def _loan_eligibility_response(self) -> str | None:
        """Apply the dataset-backed minimum score policy before loan onboarding."""
        score = int(self.profile.get("bureau_score", 0) or 0)
        if score < 600:
            return self._msg("loan_not_eligible", score=score)
        return None

    def _loan_quote(self, purpose: str, principal: int, years: float) -> str:
        """Return an indicative simple-interest and reducing-balance EMI quote."""
        annual_rate = self.LOAN_RATES.get(purpose, self.LOAN_RATES["personal"])
        simple_interest = principal * annual_rate * years / 100
        total = principal + simple_interest
        months = max(1, round(years * 12))
        monthly_rate = annual_rate / 1200
        emi = principal * monthly_rate * (1 + monthly_rate) ** months / ((1 + monthly_rate) ** months - 1)
        emi_total = emi * months
        display_years = int(years) if float(years).is_integer() else years
        lang_purposes = PURPOSE_DISPLAY.get(self.language, PURPOSE_DISPLAY["en"])
        return self._msg(
            "loan_quote",
            purpose=lang_purposes.get(purpose, purpose.title()),
            principal=principal,
            years=display_years,
            rate=annual_rate,
            simple_interest=simple_interest,
            total=total,
            emi=emi,
            emi_total=emi_total,
        )

    def _handle_loan_quote_request(self, user_text: str, ai_purpose: str | None, ai_amount):
        purpose = ai_purpose
        if self.last_loan_offer:
            purpose = self.last_loan_offer.get("purpose") or purpose
        if self.mode == "loan_onboarding":
            purpose = self.slots.get("purpose") or purpose
        if not purpose:
            purpose_ok, purpose = extract_purpose(user_text)
            if not purpose_ok:
                purpose_ok, purpose = infer_vague_loan_purpose(user_text)
            if not purpose_ok:
                purpose = None

        quote_amount_text = re.sub(
            r"\b\d+(?:\.\d+)?\s*(?:years?|year|yrs?|वर्ष|साल|વર્ષ|বছর|సంవత్సరాలు|ஆண்டுகள்|ವರ್ಷ|വർഷം|ਸਾਲ|ବର୍ଷ)\b",
            " ",
            user_text,
            flags=re.IGNORECASE,
        )
        amount_ok, parsed_amount = extract_amount(quote_amount_text)
        principal = ai_amount or (parsed_amount if amount_ok else None)
        years_ok, years = extract_years(user_text)

        if self.mode == "loan_onboarding":
            principal = self.slots.get("amount") or principal
        if not principal and self.last_loan_offer:
            principal = self.last_loan_offer.get("approved_amount")

        missing = []
        if not purpose:
            missing.append("the loan purpose (education, auto, home, business, or personal)")
        if not principal:
            missing.append("the loan amount")
        if not years_ok:
            missing.append("the tenure in years")
        if missing:
            return self._msg("loan_quote_missing", missing="; ".join(missing))
        return self._loan_quote(purpose, int(principal), years)

    def _handle_service_intent(self, intent: str) -> str | None:
        """Dispatches answers for general banking service intents."""
        if intent == "intent_kyc_status":
            if self.profile.get("kyc_verified", True):
                return self._msg("kyc_status_verified")
            return self._msg("kyc_status_due")

        if intent == "intent_kyc_update":
            return self._msg("kyc_documents")

        if intent == "intent_balance":
            bal = self.profile.get("estimated_balance", 42500)
            m_inc = self.profile.get("monthly_income", 35000)
            return self._msg("balance_response", balance=bal, monthly_income=m_inc)

        if intent == "intent_mini_statement":
            txs = self.dm.get_recent_transactions(self.customer_id, limit=3)
            lines = []
            for i, tx in enumerate(txs, 1):
                sign = "+" if tx["direction"] == "credit" else "-"
                lines.append(f"{i}.  {tx['date']} : {sign}₹{tx['amount']:,.0f} ({tx['category']} via {tx['channel']})")
            tx_formatted = "\n".join(lines)
            return self._msg("mini_statement", tx_list=tx_formatted)

        if intent == "intent_credit_score":
            score = self.profile.get("bureau_score", 720)
            grade = self.profile.get("bureau_grade", "Good / સારું")
            return self._msg("credit_score", bureau_score=score, bureau_grade=grade)

        if intent == "intent_existing_loans":
            l_cnt = self.profile.get("existing_loan_count", 0)
            l_types = ", ".join(self.profile.get("existing_loan_types", []))
            if l_cnt > 0 and l_types:
                return self._msg("existing_loans_active", loan_count=l_cnt, loan_types=l_types.title())
            return self._msg("existing_loans_none")

        if intent == "intent_block_card":
            return self._msg("block_card")

        if intent == "intent_pin_reset":
            return self._msg("pin_reset")

        if intent == "intent_branch":
            return self._msg("branch_info")

        if intent == "intent_rates":
            return self._msg("rates_info")

        if intent == "intent_helpline":
            return self._msg("helpline")

        return None

    def step(self, user_text: str) -> str:
        """Processes user voice or text input, answering multi-service queries or progressing loan onboarding."""
        intent = detect_service_intent(user_text)
        ai_purpose = None
        ai_amount = None

        # Purpose-led requests often omit the word "loan". Treat an inferred
        # purpose as a loan application unless another service was identified.
        inferred_purpose_ok, inferred_purpose = infer_vague_loan_purpose(user_text)
        if inferred_purpose_ok and not intent:
            intent = "intent_apply_loan"
            ai_purpose = ai_purpose or inferred_purpose

        # Handle interest/EMI questions before generic rate FAQs or loan-step
        # parsing, while retaining any purpose and amount already collected.
        if is_loan_quote_request(user_text):
            return self._handle_loan_quote_request(user_text, ai_purpose, ai_amount)

        # 1. Guided Loan Onboarding Mode Handling
        if self.mode == "loan_onboarding" and not self.finished:
            # If user asks a completely separate banking question (balance, kyc, block card, etc.)
            if intent and intent not in ("intent_apply_loan", "intent_greeting", "intent_unknown"):
                service_reply = self._handle_service_intent(intent)
                if service_reply:
                    return service_reply

            # Otherwise, process the current loan question
            state_name, extractor, slot_name = self.LOAN_FLOW[self.step_index]

            success, value = extractor(user_text)
            if not success:
                self.retry_count += 1
                return self._msg(f"{state_name}_retry")

            self.slots[slot_name] = value
            self.retry_count = 0
            self.step_index += 1

            if slot_name == "consent" and value is False:
                self.finished = True
                self.mode = "general"
                return self._msg("declined_consent")

            return self._get_next_loan_question()

        # 2. If user wants to apply for a loan from general mode:
        if intent == "intent_apply_loan":
            eligibility_reply = self._loan_eligibility_response()
            if eligibility_reply:
                return eligibility_reply
            self.mode = "loan_onboarding"
            self.step_index = 0
            self.slots = {}
            self.finished = False
            self.retry_count = 0
            # Pre-fill any slots inferred from the user's initial sentence
            if ai_purpose:
                self.slots["purpose"] = ai_purpose
            if ai_amount:
                self.slots["amount"] = ai_amount
            return self._get_next_loan_question()

        # 3. Check general banking service intents
        if intent:
            service_reply = self._handle_service_intent(intent)
            if service_reply:
                return service_reply

        # 4. Check greeting / welcome intents
        norm = user_text.lower().strip()
        if intent == "intent_greeting" or any(h in norm for h in ["hi", "hello", "hey", "namaste", "kem cho", "kem chho", "vanakkam", "namaskar"]):
            return self._msg("greeting")

        # 5. Friendly contextual guidance fallback for unsupported requests.
        help_prompts = {
            "hi": "माफ़ कीजिए, मुझे पूरी तरह समझ नहीं आया। आप मुझसे पूछ सकते हैं:\n•  'मेरा खाता बैलेंस कितना है?' \n•  'केवाईसी स्टेटस क्या है?' \n•  'मेरा सिबिल स्कोर क्या है?' \n•  'नया लोन अप्लाई करना है' \n•  'एटीएम कार्ड ब्लॉक करें' ",
            "gu": "માફ કરશો, હું સંપૂર્ણ સમજી શક્યો નથી. તમે પૂછી શકો છો:\n•  'મારું ખાતાનું બેલેન્સ કેટલું છે?' \n•  'કેવાયસી સ્થિતિ શું છે?' \n•  'મારો સિબિલ સ્કોર શું છે?' \n•  'નવી લોન જોઈએ છે' \n•  'કાર્ડ બ્લોક કરો' ",
            "en": "I didn't quite catch that. You can ask me:\n•  'What is my account balance?' \n•  'Check my KYC status' \n•  'What is my CIBIL score?' \n•  'Apply for a new loan' \n•  'Block my debit card' ",
        }
        return help_prompts.get(self.language, help_prompts["hi"])

